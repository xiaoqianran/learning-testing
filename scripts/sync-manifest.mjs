import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const files = [
  "src/data/lessons.ts",
  "src/data/lessons-core.ts",
  "src/data/lessons-extra.ts",
  "src/data/lessons-migrated.ts",
];
const text = files
  .filter((f) => fs.existsSync(path.join(root, f)))
  .map((f) => fs.readFileSync(path.join(root, f), "utf8"))
  .join("\n");
const slugs = [
  ...new Set(
    [...text.matchAll(/slug:\s*["']([^"']+)["']/g)].map((m) => m[1]),
  ),
];
if (slugs.length < 20) {
  console.error("few slugs", slugs.length);
  process.exit(1);
}
const out = path.join(root, "src/generated/lesson-manifest.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `/* AUTO-GENERATED by scripts/sync-manifest.mjs */
export const LESSON_SLUGS = ${JSON.stringify(slugs, null, 2)} as const;
export type LessonSlug = (typeof LESSON_SLUGS)[number];
export const LESSON_COUNT = ${slugs.length} as const;
export const MANIFEST_META = {
  total: ${slugs.length},
  generatedAt: ${JSON.stringify(new Date().toISOString())},
} as const;
`,
);
console.log("Wrote", out, slugs.length);
